import { test } from "node:test";
import assert from "node:assert/strict";
import { once } from "node:events";
import bcrypt from "bcryptjs";
import jwt from "jsonwebtoken";
import User from "../model/User.js";
import Admin from "../model/Admin.js";
import Product from "../model/Product.js";
import ImageUpload from "../model/ImageUpload.js";
import { app } from "../app.js";

test("HTTP login, session isolation, profile, cart, admin upload and origin checks", async (t) => {
  const oldSecret = process.env.JWT_SECRET;
  process.env.JWT_SECRET = "test-api-secret";
  t.after(() => { if (oldSecret === undefined) delete process.env.JWT_SECRET; else process.env.JWT_SECRET = oldSecret; });
  const user = { _id: "507f1f77bcf86cd799439011", name: "Alice", email: "alice@example.com", password: "hash", cart: [], sessionVersion: 0, async save() {} };
  const admin = { _id: "507f1f77bcf86cd799439012", username: "admin", password: "hash" };
  t.mock.method(User, "findOne", async () => user);
  t.mock.method(User, "findById", async (id) => String(id) === user._id ? user : null);
  t.mock.method(User, "updateOne", async () => { user.sessionVersion++; });
  t.mock.method(Product, "find", async () => []);
  t.mock.method(Admin, "findOne", async () => admin);
  t.mock.method(Admin, "findById", async (id) => String(id) === admin._id ? admin : null);
  t.mock.method(bcrypt, "compare", async () => true);
  const server = app.listen(0, "127.0.0.1");
  await once(server, "listening");
  t.after(() => { server.closeAllConnections(); server.close(); });
  const base = `http://127.0.0.1:${server.address().port}`;
  const request = (path, options) => fetch(base + path, options);
  const json = (body) => ({ method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify(body) });

  const spoof = await request("/api/cart", { headers: { "x-user-id": user._id } });
  assert.equal(spoof.status, 401);
  const updateSpoof = await request("/api/auth/update", { ...json({ userId: user._id, name: "Stolen" }), method: "PUT" });
  assert.equal(updateSpoof.status, 401);
  const login = await request("/api/auth/login", json({ username: user.name, password: "password" }));
  assert.equal(login.status, 200);
  const cookie = login.headers.get("set-cookie").split(";")[0];
  assert.match(login.headers.get("set-cookie"), /HttpOnly/);
  assert.match(login.headers.get("set-cookie"), /SameSite=Lax/);
  const me = await request("/api/auth/me", { headers: { Cookie: cookie } });
  assert.equal((await me.json())._id, user._id);
  const profile = await request("/api/auth/update", { ...json({ userId: "someone-else", name: "Alice" }), method: "PUT", headers: { "Content-Type": "application/json", Cookie: cookie } });
  assert.equal(profile.status, 200);
  assert.equal((await profile.json())._id, user._id);
  const cart = await request("/api/cart", { headers: { Cookie: cookie } });
  assert.equal(cart.status, 200);
  assert.deepEqual((await cart.json()).cart, []);
  const badOrigin = await request("/api/auth/update", { ...json({ name: "Attacker" }), method: "PUT", headers: { "Content-Type": "application/json", Cookie: cookie, Origin: "https://untrusted.example" } });
  assert.equal(badOrigin.status, 403);
  const noAdmin = await request("/api/admin/uploads/presign", { ...json({ contentType: "image/jpeg", size: 10 }), headers: { "Content-Type": "application/json", Cookie: cookie } });
  assert.equal(noAdmin.status, 401);
  const adminLogin = await request("/api/admin/login", json({ username: "admin", password: "password" }));
  assert.equal(adminLogin.status, 200);
  const token = (await adminLogin.json()).token;
  assert.equal(jwt.verify(token, process.env.JWT_SECRET).role, "admin");
  const tooLarge = await request("/api/admin/uploads/presign", { ...json({ category: "laptop", contentType: "image/jpeg", size: 6 * 1024 * 1024 }), headers: { "Content-Type": "application/json", Authorization: `Bearer ${token}` } });
  assert.equal(tooLarge.status, 400);
  const created = [];
  t.mock.method(ImageUpload, "create", async (record) => { created.push(record); return record; });
  for (const [key, value] of Object.entries({ AWS_REGION: "us-east-2", AWS_S3_BUCKET: "test-images", AWS_ACCESS_KEY_ID: "test", AWS_SECRET_ACCESS_KEY: "test" })) {
    const previous = process.env[key]; process.env[key] = value;
    t.after(() => { if (previous === undefined) delete process.env[key]; else process.env[key] = previous; });
  }
  const upload = await request("/api/admin/uploads/presign", { ...json({ category: "laptop", contentType: "image/jpeg", size: 10 }), headers: { "Content-Type": "application/json", Authorization: `Bearer ${token}` } });
  assert.equal(upload.status, 200);
  assert.match((await upload.json()).key, /^products\/laptop\//);
  assert.equal(String(created[0].adminId), admin._id);
  const logout = await request("/api/auth/logout", { method: "POST", headers: { Cookie: cookie } });
  assert.equal(logout.status, 200);
  const invalidated = await request("/api/auth/me", { headers: { Cookie: cookie } });
  assert.equal(invalidated.status, 401);
});
