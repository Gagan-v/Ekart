import "./config/env.js";
import express from "express";
import cookieParser from "cookie-parser";
import cors from "cors";
import helmet from "helmet";
import morgan from "morgan";
import authRoutes from "./routes/authRoutes.js";
import adminRoutes from "./routes/adminRoutes.js";
import productRoutes from "./routes/productsRoutes.js";
import reviewRoutes from "./routes/reviewRoutes.js";
import cartRoutes from "./routes/cartRoutes.js";
import uploadRoutes from "./routes/uploadRoutes.js";
import { allowedOrigins, checkOrigin, authLimiter } from "./middleware/requestPolicy.js";

export const app = express();
if (process.env.TRUST_PROXY_HOPS) app.set("trust proxy", Number(process.env.TRUST_PROXY_HOPS));
app.disable("x-powered-by");
app.use(helmet());
app.use(checkOrigin);
app.use(cors({ origin: allowedOrigins(), credentials: true }));
app.use(express.json({ limit: "1mb" }));
app.use(cookieParser());
app.use(morgan("dev"));
app.use("/api", (_req, res, next) => { res.set("Cache-Control", "no-store"); next(); });
app.get("/", (_req, res) => res.send("API is running..."));
app.get("/api/health", (_req, res) => res.json({ status: "ok" }));
app.use(["/api/auth/login", "/api/auth/register", "/api/admin/login"], authLimiter());
app.use("/api/auth", authRoutes);
app.use("/api/admin", adminRoutes);
app.use("/api/admin/products", productRoutes);
app.use("/api/reviews", reviewRoutes);
app.use("/api/cart", cartRoutes);
app.use("/api/admin/uploads", uploadRoutes);
app.use((_req, res) => res.status(404).json({ message: "Endpoint not found" }));
app.use((error, _req, res, _next) => {
  if (error.type === "entity.parse.failed") return res.status(400).json({ message: "Invalid JSON" });
  if (error.type === "entity.too.large") return res.status(413).json({ message: "Request is too large" });
  console.error("API error", { code: error.name, message: error.message });
  res.status(500).json({ message: "Could not complete request" });
});
